// Shared fixtures for the end-to-end specs.
//
// Every test gets:
//   - freshly wiped + seeded Auth/Firestore emulators (auto fixture), so specs
//     are independent and can run in any order;
//   - browser contexts whose /firebase-init.js is swapped for a copy of the
//     real one that points at the emulators (connectAuthEmulator +
//     connectFirestoreEmulator, projectId demo-cccs). No production code
//     changes are needed;
//   - a hard block on every production Firebase / waste endpoint. If a page
//     ever tries to reach them the test fails.
