// Sends one McAssist message through the real UI and returns the JSON the
// real /api/ai-chat endpoint answered with.
export async function askMcAssist(page, message) {
  const input = page.getByRole("textbox", { name: "Message McAssist" });
  await input.fill(message);
  const responsePromise = page.waitForResponse(
    (r) => /\/api\/(ai-chat|mcassist)$/.test(new URL(r.url()).pathname) && r.request().method() === "POST",
    { timeout: 45000 },
  );
  await page.getByRole("button", { name: "Send message", exact: true }).click();
  const response = await responsePromise;
  const body = await response.json().catch(() => ({}));
  return { status: response.status(), body };
}

// Clicks a pending-plan button (e.g. its confirmLabel) and returns the JSON of
// the confirm request.
export async function resolvePending(page, label) {
  const responsePromise = page.waitForResponse(
    (r) => /\/api\/(ai-chat|mcassist)$/.test(new URL(r.url()).pathname) && r.request().method() === "POST",
    { timeout: 45000 },
  );
  await page.getByRole("button", { name: label, exact: true }).last().click();
  const response = await responsePromise;
  const request = response.request().postDataJSON?.() || {};
  return { status: response.status(), body: await response.json().catch(() => ({})), request };
}

// Clicks a control inside a modal sheet by its on-screen position (real hit
// testing, like a finger). Playwright's locator.click() in WebKit iPhone
// emulation first "scrolls into view" a sticky footer inside the scroll-locked
// sheet, which moves the visual viewport so the click lands outside the page.
export async function pressVisible(page, locator) {
  await expect(locator).toBeVisible();
  await expect(locator).toBeEnabled();
  const box = await locator.boundingBox();
  const view = page.viewportSize();
  const inView = box && view && box.y >= 0 && box.x >= 0 && box.y + box.height <= view.height && box.x + box.width <= view.width;
  if (!inView) return locator.click();
  await page.mouse.click(box.x + box.width / 2, box.y + box.height / 2);
}

// Calls an API route from inside the page with the signed-in user's real
// Firebase ID token (waits for Auth to restore the session first).
export async function pageApi(page, path, body) {
  await page.waitForFunction(() => Boolean(window.__e2eFirebase?.auth), null, { timeout: 20000 });
  return page.evaluate(
    async ({ path, body }) => {
      const { auth } = window.__e2eFirebase;
      await auth.authStateReady();
      const token = await auth.currentUser.getIdToken();
      const r = await fetch(path, {
        method: body ? "POST" : "GET",
        headers: { "Content-Type": "application/json", Authorization: "Bearer " + token },
        body: body ? JSON.stringify(body) : undefined,
      });
      return { status: r.status, body: await r.json().catch(() => ({})) };
    },
    { path, body },
  );
}

// Draws a short squiggle on a signature canvas using pointer events.
export async function drawSignature(page, canvas) {
  await canvas.scrollIntoViewIfNeeded();
  const box = await canvas.boundingBox();
  if (!box) throw new Error("Signature canvas is not visible");
  const x = box.x + 20;
  const y = box.y + box.height / 2;
  await page.mouse.move(x, y);
  await page.mouse.down();
  for (let i = 1; i <= 12; i++) await page.mouse.move(x + i * 12, y + (i % 2 ? -18 : 18), { steps: 2 });
  await page.mouse.up();
}

// ---------------------------------------------------------- data helpers
export async function shiftsFor(admin, uid, storeId = SEED.store.id) {
  const snap = await admin.db.collection(`stores/${storeId}/Shifts`).where("userId", "==", uid).get();
  return snap.docs.map((d) => ({ id: d.id, ...d.data() }));
}

export async function userDoc(admin, uid) {
  const snap = await admin.db.doc("users/" + uid).get();
  return snap.exists ? snap.data() : null;
}

export async function authUserExists(admin, uid) {
  try {
    await admin.auth.getUser(uid);
    return true;
  } catch (error) {
    if (error.code === "auth/user-not-found") return false;
    throw error;
  }
}

