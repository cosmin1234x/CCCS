const SDK = "https://www.gstatic.com/firebasejs/10.12.0";

// Build the emulator variant of firebase-init.js from the real file so the
// app config stays identical apart from the project ID.
export function emulatorFirebaseInit() {
  const source = readFileSync(resolve("firebase-init.js"), "utf8");
  const match = source.match(/const\s+firebaseConfig\s*=\s*(\{[\s\S]*?\});/);
  if (!match) throw new Error("Could not find firebaseConfig in firebase-init.js");
  const config = Function('"use strict";return (' + match[1] + ");")();
  config.projectId = E2E_PROJECT_ID;
  config.authDomain = E2E_PROJECT_ID + ".firebaseapp.com";
  delete config.measurementId;
  const sdk = source.match(/https:\/\/www\.gstatic\.com\/firebasejs\/[\d.]+/)?.[0] || SDK;
  const [fsHost, fsPort] = FIRESTORE_HOST.split(":");
  return `// e2e: emulator build of firebase-init.js (generated by tests/e2e/fixtures.mjs)
import { initializeApp } from "${sdk}/firebase-app.js";
import { getAuth, connectAuthEmulator } from "${sdk}/firebase-auth.js";
import { getFirestore, connectFirestoreEmulator } from "${sdk}/firebase-firestore.js";
const firebaseConfig = ${JSON.stringify(config, null, 2)};
const app = initializeApp(firebaseConfig);
const auth = getAuth(app);
connectAuthEmulator(auth, "http://${AUTH_HOST}", { disableWarnings: true });
const db = getFirestore(app);
connectFirestoreEmulator(db, "${fsHost}", ${Number(fsPort)});
const analytics = null;
window.__e2eFirebase = { app, auth, db };
export { app, auth, db, analytics };
`;
}

// Matched against the HOSTNAME only: the Auth emulator legitimately serves
// paths such as http://127.0.0.1:9099/identitytoolkit.googleapis.com/…
const PRODUCTION_HOSTS =
  /(^|\.)(firestore\.googleapis\.com|identitytoolkit\.googleapis\.com|securetoken\.googleapis\.com|firebaseinstallations\.googleapis\.com|firebase\.googleapis\.com|firebaseio\.com|haylewaster\.vercel\.app|api\.openai\.com)$/;

// The Firebase web SDK and Google Fonts are fetched once per test worker and
// then served from memory, so each new browser context does not download
// them again (a big speed-up, especially for WebKit).
const CDN = /^https:\/\/(www\.gstatic\.com\/firebasejs\/|fonts\.googleapis\.com\/|fonts\.gstatic\.com\/)/;
const cdnCache = new Map();

async function serveCdn(route) {
  const url = route.request().url();
  if (route.request().method() !== "GET") return route.continue();
  let hit = cdnCache.get(url);
  if (!hit) {
    try {
      const response = await route.fetch();
      if (!response.ok()) return route.fulfill({ response });
      // body() is already decoded: drop encoding/length headers.
      const headers = Object.fromEntries(
        Object.entries(response.headers()).filter(([k]) => !/^(content-encoding|content-length|transfer-encoding)$/i.test(k)),
      );
      hit = { status: response.status(), headers, body: await response.body() };
      cdnCache.set(url, hit);
    } catch {
      return route.continue().catch(() => {});
    }
  }
  return route.fulfill({ status: hit.status, headers: hit.headers, body: hit.body });
}

// Note: the emulator speaks HTTP/1.1 (six connections per browser context)
// and Playwright's WebKit on Windows keeps connections of pages it has left.
// Specs that visit many pages open a fresh context per page (layout.spec).
export async function prepareContext(context, blocked) {
  const init = emulatorFirebaseInit();
  await context.route(/\/firebase-init\.js(\?.*)?$/, (route) =>
    route.fulfill({ status: 200, contentType: "text/javascript; charset=utf-8", body: init }),
  );
  await context.route(CDN, serveCdn);
  await context.route((url) => PRODUCTION_HOSTS.test(url.hostname), (route) => {
    blocked.push(route.request().method() + " " + route.request().url());
    return route.abort("blockedbyclient");
  });
}

export const test = base.extend({
  // Wipe + seed before every test (runs even if the test does not use it).
  seeded: [
    async ({}, use) => {
      await resetAndSeed();
      // Fresh fake upstreams too (ignore if a spec runs without them).
      await Promise.all(
        ["http://127.0.0.1:4011/__e2e/reset", "http://127.0.0.1:4010/__e2e/reset"].map((url) =>
          fetch(url, { method: "POST", body: "{}" }).catch(() => null),
        ),
      );
      await use(SEED);
    },
    { auto: true },
  ],
  blockedRequests: [
    async ({}, use) => {
      const blocked = [];
      await use(blocked);
      expect(blocked, "The app tried to reach a production endpoint").toEqual([]);
    },
    { auto: true },
  ],
  context: async ({ context, blockedRequests }, use) => {
    await prepareContext(context, blockedRequests);
    await use(context);
  },
  admin: async ({}, use) => {
    await use(adminFor("e2e-tests"));
  },
  // Opens a second, fully isolated browser session (e.g. crew + manager side
  // by side) with the same emulator routing and device settings. Pass
  // { storageState } to reuse a signed-in session in a fresh browser context.
  newSession: async ({ browser, blockedRequests }, use, testInfo) => {
    const contexts = [];
    await use(async (options = {}) => {
      const { baseURL, viewport, userAgent, deviceScaleFactor, isMobile, hasTouch, locale, timezoneId, reducedMotion } =
        testInfo.project.use;
      const context = await browser.newContext({
        baseURL,
        viewport,
        userAgent,
        deviceScaleFactor,
        isMobile,
        hasTouch,
        locale,
        timezoneId,
        reducedMotion,
        ...options,
      });
      contexts.push(context);
      await prepareContext(context, blockedRequests);
      return context.newPage();
    });
    await Promise.all(contexts.map((c) => c.close()));
  },
});

// ------------------------------------------------------------ UI helpers
export async function signIn(page, who) {
  const user = typeof who === "string" ? SEED.users[who] : who;
  await page.goto("/");
  await page.getByLabel(/email/i).fill(user.email);
  await page.getByLabel(/^password/i).fill(user.password || SEED.password);
  const roleData = page
    .waitForResponse((r) => new URL(r.url()).pathname === "/api/portal-data", { timeout: 30000 })
    .catch(() => null);
  await page.getByRole("button", { name: /^sign in/i }).click();
  await page.waitForURL(/\/main(\.html)?(\?|$)/, { timeout: 20000 });
  await roleData;
  await waitForHub(page);
  return user;
}

// The shell renders first; portal-enhancements.js then loads role data from
// /api/portal-data and applies the role UI (it injects the verification link
// into the navigation). Wait for that so tests act on the finished page.
export async function waitForHub(page) {
  await expect(page.locator("#content")).not.toBeEmpty({ timeout: 20000 });
  await expect(page.locator('a[href^="/verification.html"]').first()).toBeAttached({ timeout: 20000 });
}

// Sign-out triggers two navigations (the click handler and the auth listener),
// so poll the URL instead of waiting for a single navigation event.
export async function expectSignedOut(page) {
  await expect(page).toHaveURL(/127\.0\.0\.1:\d+\/(index\.html)?(\?.*)?$/, { timeout: 20000 });
  await expect(page.getByRole("button", { name: /^sign in/i })).toBeVisible();
}

// The primary navigation is the sidebar on desktop and the bottom bar on
// phones/tablets; return whichever is visible.
export function mainNav(page) {
  return page
    .getByRole("navigation", { name: /Main navigation|Mobile navigation/ })
    .filter({ visible: true })
    .first();
}

